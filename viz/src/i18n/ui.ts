const dictionaries: Record<Lang, Record<UIKey, string>> = { en, es };

export function t(lang: Lang, key: UIKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** A t() bound to one language, for components. */
export function useT(lang: Lang) {
  return (key: UIKey, vars?: Record<string, string | number>) => t(lang, key, vars);
}

export function localePath(lang: Lang, path = ''): string {
  const clean = path.replace(/^\/+/, '');
  return `${import.meta.env.BASE_URL.replace(/\/$/, '')}/${lang}/${clean}`;
}

